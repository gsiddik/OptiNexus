// @vitest-environment jsdom
import { cleanup, render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { afterEach, expect, it } from 'vitest';
import { HelpInput, HelpLabel } from './FieldControls';
afterEach(cleanup);

it('shows help only from the info symbol and preserves field/error associations', async () => {
  render(<><HelpLabel>Name<HelpInput help="Enter a readable name." aria-describedby="error" /></HelpLabel><span id="error">Name is required</span></>);
  const input = screen.getByRole('textbox', { name: 'Name' });
  const info = screen.getByRole('button', { name: 'Field information' });
  const tip = screen.getByRole('tooltip');
  await userEvent.hover(input);
  expect(tip.className).not.toContain('field-tooltip-open');
  input.focus();
  expect(tip.className).not.toContain('field-tooltip-open');
  await userEvent.hover(info);
  expect(tip.className).toContain('field-tooltip-open');
  expect(input.getAttribute('aria-describedby')?.split(' ')).toEqual(['error', tip.id]);
  await userEvent.unhover(info);
  expect(tip.className).not.toContain('field-tooltip-open');
  info.focus();
  await userEvent.keyboard('{Escape}');
  expect(tip.className).not.toContain('field-tooltip-open');
  expect(document.activeElement).toBe(info);
});

it('keeps readonly fields readable and checkbox labels clickable', async () => {
  render(<><HelpLabel>Code<HelpInput readOnly value="Generated on save" help="Generated by the system." /></HelpLabel><HelpLabel>Auto Renew<HelpInput type="checkbox" help="Renew automatically." /></HelpLabel></>);
  expect((screen.getByLabelText('Code') as HTMLInputElement).readOnly).toBe(true);
  await userEvent.click(screen.getByText('Auto Renew'));
  expect((screen.getByRole('checkbox', { name: 'Auto Renew' }) as HTMLInputElement).checked).toBe(true);
});
