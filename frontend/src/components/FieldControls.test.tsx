// @vitest-environment jsdom
import { cleanup, render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { afterEach, expect, it } from 'vitest';
import { HelpInput } from './FieldControls';

afterEach(cleanup);

it('shows keyboard help without changing the field name or losing error descriptions', async () => {
  render(<><label>Name<HelpInput help="Enter a readable name." aria-describedby="error" /></label><span id="error">Name is required</span></>);
  const input = screen.getByRole('textbox', { name: 'Name' });
  await userEvent.tab();
  const tip = screen.getByRole('tooltip');
  expect(tip.className).toContain('field-tooltip-open');
  expect(input.getAttribute('aria-describedby')?.split(' ')).toEqual(['error', tip.id]);
  expect(input.closest('label')?.contains(tip)).toBe(false);
  await userEvent.keyboard('{Escape}');
  expect(tip.className).not.toContain('field-tooltip-open');
  expect(document.activeElement).toBe(input);
});

it('shows mouse help on a readonly system code', async () => {
  render(<label>Code<HelpInput readOnly value="Generated on save" help="Generated by the system." /></label>);
  await userEvent.hover(screen.getByRole('textbox', { name: 'Code' }));
  expect(screen.getByRole('tooltip').className).toContain('field-tooltip-open');
  await userEvent.unhover(screen.getByRole('textbox', { name: 'Code' }));
  expect(screen.getByRole('tooltip').className).not.toContain('field-tooltip-open');
});
